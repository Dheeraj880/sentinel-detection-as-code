"""Generate MITRE ATT&CK coverage from rule tags.

Writes:
  coverage/attack-layer.json  - layer for MITRE ATT&CK Navigator
  coverage/COVERAGE.md        - readable table for the README
"""
import json
import pathlib
from detections import load_detections

OUT = pathlib.Path("coverage")


def main():
    techniques = {}  # technique ID -> {"tactics": set, "rules": list}
    for det in load_detections():
        tags = det["tags"]
        tactics = sorted(t.split(".", 1)[1] for t in tags
                         if t.startswith("attack.") and not t.startswith("attack.t"))
        for tag in tags:
            if tag.startswith("attack.t"):
                tid = tag.split(".", 1)[1].upper()
                entry = techniques.setdefault(tid, {"tactics": set(), "rules": []})
                entry["tactics"].update(tactics)
                entry["rules"].append(det["title"])

    layer = {
        "name": "sentinel-detection-as-code coverage",
        "domain": "enterprise-attack",
        "description": "Techniques covered by detections in this repo. Score = number of detections.",
        "versions": {"layer": "4.5"},
        "techniques": [
            {"techniqueID": tid, "score": len(e["rules"]),
             "comment": "; ".join(e["rules"]), "enabled": True}
            for tid, e in sorted(techniques.items())
        ],
        "gradient": {"colors": ["#d6f5d6", "#2b8a3e"], "minValue": 1, "maxValue": 3},
    }

    lines = [
        "# ATT&CK Coverage",
        "",
        "Generated by `coverage.py` from rule tags. Do not edit by hand.",
        "",
        f"**{len(techniques)} techniques** covered by "
        f"**{len({r for e in techniques.values() for r in e['rules']})} detections**.",
        "",
        "| Technique | Tactics | Detections |",
        "|---|---|---|",
    ]
    for tid, e in sorted(techniques.items()):
        url = f"https://attack.mitre.org/techniques/{tid.replace('.', '/')}/"
        lines.append(f"| [{tid}]({url}) | {', '.join(sorted(e['tactics']))} | {'<br>'.join(e['rules'])} |")

    OUT.mkdir(exist_ok=True)
    (OUT / "attack-layer.json").write_text(json.dumps(layer, indent=2) + "\n", encoding="utf-8", newline="\n")
    (OUT / "COVERAGE.md").write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")
    print(f"{len(techniques)} techniques covered")


if __name__ == "__main__":
    main()